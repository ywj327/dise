export function getCharacter(q1: Q1Type, q2: Q2Type): Character {
  return characterMap[q1]?.[q2] ?? { name: '探索者', desc: '正在形成中。' }
}

export function calculateResult(answers: Record<number, string>): Result {
  const counts = { q1: {} as Record<string, number>, q2: {} as Record<string, number>, q3: {} as Record<string, number>, q4: {} as Record<string, number> }

  questions.forEach((q) => {
    const answer = answers[q.id]
    if (!answer) return
    const key = `q${q.quadrant}` as keyof typeof counts
    counts[key][answer] = (counts[key][answer] || 0) + 1
  })

  const topType = (obj: Record<string, number>) =>
    Object.entries(obj).sort((a, b) => b[1] - a[1])[0]?.[0] ?? ''

  return {
    q1: topType(counts.q1) as Q1Type,
    q2: topType(counts.q2) as Q2Type,
    q3: topType(counts.q3) as Q3Type,
    q4: topType(counts.q4) as Q4Type,
  }
}

