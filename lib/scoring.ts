// ─── Signal System ────────────────────────────────────────────────────────────

export type Signal = 'approval' | 'security' | 'autonomy' | 'control' | 'achievement' | 'suppression'
export type SignalScores = Record<Signal, number>

export const ZERO_SIGNALS: SignalScores = {
  approval: 0, security: 0, autonomy: 0, control: 0, achievement: 0, suppression: 0,
}

const TYPE_TO_SIGNAL: Record<string, Signal> = {
  '回避型': 'autonomy',
  '焦虑型': 'security',
  '表演型': 'approval',
  '安全型': 'security',
  '认可驱动': 'approval',
  '自主驱动': 'autonomy',
  '意义驱动': 'achievement',
  '成就驱动': 'achievement',
  '方向未定型': 'control',
  '执行卡壳型': 'achievement',
  '身份过渡型': 'autonomy',
  '过载运转型': 'control',
  '能力拓展型': 'achievement',
  '生活方式型': 'autonomy',
  '影响力型': 'approval',
  '稳定感型': 'security',
}

export function computeSignals(answers: Record<number, string>): SignalScores {
  const scores: SignalScores = { ...ZERO_SIGNALS }
  for (const type of Object.values(answers)) {
    const signal = TYPE_TO_SIGNAL[type]
    if (signal) scores[signal]++
  }
  return scores
}

export function topTwoSignals(scores: SignalScores): [Signal, Signal] {
  const sorted = (Object.entries(scores) as [Signal, number][]).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
  return [sorted[0][0], sorted[1][0]]
}

export function topSignal(scores: SignalScores): Signal {
  return topTwoSignals(scores)[0]
}

